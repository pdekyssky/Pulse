/**
 * Shared Tailwind class names for settings form controls.
 */

export function inputClassName() {
  return 'w-full rounded-lg border border-gray-200 bg-white px-3 py-2 text-sm text-gray-900 shadow-sm placeholder:text-gray-400 focus:border-pulse-500 focus:ring-2 focus:ring-pulse-500/20 focus:outline-none'
}

export function selectClassName() {
  return inputClassName()
}
